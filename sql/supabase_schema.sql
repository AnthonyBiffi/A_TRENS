CREATE TABLE IF NOT EXISTS public.avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(20) NOT NULL,
    tipo_transporte VARCHAR(50) NOT NULL,
    linha VARCHAR(120) NOT NULL,
    estacao VARCHAR(120) NOT NULL,
    data_viagem DATE NOT NULL,
    hora_viagem TIME NOT NULL,
    intervalo_medio_minutos INTEGER NULL,
    nota_espera INTEGER NOT NULL CHECK (nota_espera BETWEEN 0 AND 5),
    nota_lotacao INTEGER NOT NULL CHECK (nota_lotacao BETWEEN 0 AND 5),
    nota_qualidade INTEGER NOT NULL CHECK (nota_qualidade BETWEEN 0 AND 5),
    comentario TEXT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices para acelerar a Consulta Rápida do Trem e o Dashboard Admin
CREATE INDEX IF NOT EXISTS idx_avaliacoes_criado_em ON public.avaliacoes (criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_avaliacoes_transporte_linha ON public.avaliacoes (tipo_transporte, linha, estacao);

-- Habilita Row Level Security (RLS) e libera acesso para a API do projeto A3
ALTER TABLE public.avaliacoes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura publica avaliacoes" ON public.avaliacoes;
CREATE POLICY "Permitir leitura publica avaliacoes"
    ON public.avaliacoes
    FOR SELECT
    TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "Permitir insercao publica avaliacoes" ON public.avaliacoes;
CREATE POLICY "Permitir insercao publica avaliacoes"
    ON public.avaliacoes
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT (id, tipo_transporte, linha, estacao, intervalo_medio_minutos, criado_em,
              nota_espera, nota_lotacao, nota_qualidade)
    ON public.avaliacoes TO anon, authenticated;
GRANT INSERT (nome, cpf, tipo_transporte, linha, estacao, data_viagem, hora_viagem,
              intervalo_medio_minutos, nota_espera, nota_lotacao, nota_qualidade, comentario)
    ON public.avaliacoes TO anon, authenticated;
